# -*- coding: utf-8 -*-
"""Build the whale-girl pixel asset from qa/ref_whale.png (DeepSeek mascot art).

Background is removed by flood-filling the near-white border region (so the
white apron/headdress inside the character survive), then the bust is
downsampled to a coarse pixel grid, cooled toward blue and quantised.
"""
import base64
import sys

import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, ".")
from engine import frame as FRM
from engine import palette as P

SRC = "qa/ref_whale.png"
OUT = "engine/god_pixels.py"
CROP = (110, 44, 288, 248)     # head + shoulders close-up
W, H = 48, 54                  # pixel grid (2 subpixels / cell row -> 27 rows)

im = Image.open(SRC).convert("RGB").crop(CROP)

# ---- background removal: flood fill the near-white border region ----------
a = np.asarray(im).astype(np.float32)
lum = a.mean(axis=2)
sat = a.max(axis=2) - a.min(axis=2)
near_white = ((lum > 226) & (sat < 26)).astype(np.uint8) * 255
mask = Image.fromarray(near_white, "L")
w, h = mask.size
for seed in ((0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1),
             (w // 2, 0), (w // 2, h - 1), (0, h // 2), (w - 1, h // 2)):
    if mask.getpixel(seed) == 255:
        ImageDraw.floodfill(mask, seed, 128)
bg = np.asarray(mask) == 128
alpha = np.where(bg, 0.0, 1.0)
# soften the edge
alpha_img = Image.fromarray((alpha * 255).astype(np.uint8), "L").filter(Image.Filter.GaussianBlur(0.6)) if hasattr(Image, "Filter") else Image.fromarray((alpha * 255).astype(np.uint8), "L")
rgba = np.dstack([np.asarray(im).astype(np.uint8), np.asarray(alpha_img, dtype=np.uint8)])
small = np.asarray(Image.fromarray(rgba, "RGBA").resize((W, H), Image.LANCZOS)).astype(np.float32)
rgb, al = small[:, :, :3], small[:, :, 3] / 255.0

# ---- cool the palette toward blue, keep contrast --------------------------
rgb[:, :, 2] = np.clip(rgb[:, :, 2] * 1.04 + 8.0, 0, 255)
rgb = np.clip((rgb - 128.0) * 1.06 + 128.0, 0, 255)

pal_img = Image.fromarray(rgb.astype(np.uint8), "RGB")
q = pal_img.quantize(colors=36, method=Image.MEDIANCUT)
pal = q.getpalette()[:36 * 3]
palette = [(0, 0, 0)] + [tuple(pal[i * 3:i * 3 + 3]) for i in range(36)]
idx = np.asarray(q, dtype=np.uint8).copy()
idx[al < 0.45] = 0

with open(OUT, "w", encoding="utf-8") as f:
    f.write('"""Whale-girl pixel asset: generated by tools/make_god_pixels.py"""\n')
    f.write("W = %d\nH = %d\n" % (W, H))
    f.write("PALETTE = %r\n" % (palette,))
    f.write("DATA_B64 = (\n")
    b64 = base64.b64encode(idx.tobytes()).decode("ascii")
    for i in range(0, len(b64), 100):
        f.write('    "%s"\n' % b64[i:i + 100])
    f.write(")\n\n\n")
    f.write("def decode():\n")
    f.write("    import base64\n")
    f.write("    import numpy as np\n")
    f.write("    raw = base64.b64decode(DATA_B64)\n")
    f.write("    return np.frombuffer(raw, dtype=np.uint8).reshape(H, W)\n")
print("wrote", OUT, W, "x", H)

